# If-Else Example
num = 15
if num % 2 == 0:
    print(num, "is even")
else:
    print(num, "is odd")

# For Loop Example
print("For loop 0-4:")
for i in range(5):
    print(i)

# While Loop Example
print("While loop 0-4:")
count = 0
while count < 5:
    print(count)
    count += 1

# Break Example
print("Break example:")
for i in range(5):
    if i == 3:
        break
    print(i)

# Continue Example
print("Continue example:")
for i in range(5):
    if i == 3:
        continue
    print(i)
